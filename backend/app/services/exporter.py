NUMBER_WORDS = {1: "ONE", 2: "TWO", 3: "THREE", 4: "FOUR", 5: "FIVE", 6: "SIX", 7: "SEVEN", 8: "EIGHT"}


def exam_note(paper: dict) -> str:
    n = paper["module_count"]
    word = NUMBER_WORDS.get(n, str(n))
    if n == 1:
        return "Answer any ONE full question."
    return f"Answer any {word} full questions, choosing ONE full question from each module."


def _cell(cell, text, bold=False, align=None, size=11, italic=False):
    cell.text = ""
    p = cell.paragraphs[0]
    run = p.add_run(text)
    run.bold, run.italic = bold, italic
    run.font.size = Pt(size)
    if align:
        p.alignment = align
    return p


def _no_borders(cell, keep: str = ""):
    """Hide a cell's borders except the side named in `keep`."""
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn

    borders = OxmlElement("w:tcBorders")
    for side in ("top", "left", "bottom", "right"):
        if side == keep:
            continue
        el = OxmlElement(f"w:{side}")
        el.set(qn("w:val"), "nil")
        borders.append(el)
    cell._tc.get_or_add_tcPr().append(borders)


def exam_docx(course, paper: dict, scheme: bool = False) -> bytes:
    from docx.shared import Cm

    doc = Document()
    for section in doc.sections:
        section.left_margin = section.right_margin = Cm(1.8)
        section.top_margin = section.bottom_margin = Cm(1.6)
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(11)

    # USN boxes + course code
    top = doc.add_table(rows=1, cols=12)
    top.style = "Table Grid"
    top.autofit = False
    top_widths = [Cm(1.4)] + [Cm(0.75)] * 10 + [Cm(8.5)]
    for col, width in zip(top.columns, top_widths):
        col.width = width
    for cell, width in zip(top.rows[0].cells, top_widths):
        cell.width = width
    _cell(top.rows[0].cells[0], "USN", bold=True, size=10)
    _cell(top.rows[0].cells[11], course.code or "", bold=True, align=WD_ALIGN_PARAGRAPH.RIGHT, size=12)
    _no_borders(top.rows[0].cells[11], keep="left")
    _no_borders(top.rows[0].cells[0], keep="right")

    def centered(text, size=12, bold=True, space=2):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.space_after = Pt(space)
        run = p.add_run(text)
        run.bold = bold
        run.font.size = Pt(size)
        return p

    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    heading = " ".join(x for x in [f"{paper['semester']} Semester" if paper["semester"] else "", "B.E. Degree",
                                    "Examination" if paper["pattern"] == "see" else paper["pattern_label"]] if x)
    if paper["session"]:
        heading += f", {paper['session']}"
    centered(heading, 13)
    centered(course.name, 14)
    if scheme:
        centered("Scheme of Valuation", 12)

    meta = doc.add_table(rows=1, cols=2)
    _cell(meta.rows[0].cells[0], f"Time: {paper['duration']}", bold=True)
    _cell(meta.rows[0].cells[1], f"Max. Marks: {paper['max_marks']}", bold=True, align=WD_ALIGN_PARAGRAPH.RIGHT)
    note = doc.add_paragraph()
    note.paragraph_format.space_before = Pt(4)
    r = note.add_run("Note: ")
    r.bold = True
    note.add_run(exam_note(paper) + "  M: Marks, L: Bloom's level, C: Course outcome.").italic = True

    table = doc.add_table(rows=1, cols=6)
    table.style = "Table Grid"
    table.autofit = False
    widths = [Cm(1.4), Cm(0.8), Cm(11.6), Cm(1.0), Cm(1.0), Cm(1.4)]
    for col, width in zip(table.columns, widths):
        col.width = width

    def new_row():
        cells = table.add_row().cells
        for cell, width in zip(cells, widths):
            cell.width = width
        return cells
    for cell, width in zip(table.rows[0].cells, widths):
        cell.width = width
    for cell, text in zip(table.rows[0].cells, ["Q.No", "", "Question" if not scheme else "Question and scheme", "M", "L", "C"]):
        _cell(cell, text, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, size=10)

    number = 0
    for mi, module in enumerate(paper["modules"]):
        row = new_row()
        merged = row[0].merge(row[5])
        _cell(merged, f"Module - {mi + 1}" + (f"  ({module['topic']})" if scheme else ""), bold=True,
              align=WD_ALIGN_PARAGRAPH.CENTER)
        for qi, question in enumerate(module.get("questions", [])):
            number += 1
            if qi > 0:
                row = new_row()
                _cell(row[0].merge(row[5]), "OR", bold=True, align=WD_ALIGN_PARAGRAPH.CENTER)
            for pi, part in enumerate(question["parts"]):
                row = new_row()
                _cell(row[0], f"Q.{number:02d}" if pi == 0 else "", bold=True, align=WD_ALIGN_PARAGRAPH.CENTER)
                _cell(row[1], "abcdef"[pi], align=WD_ALIGN_PARAGRAPH.CENTER)
                para = _cell(row[2], part["text"])
                if scheme:
                    for line in part.get("scheme", []):
                        extra = row[2].add_paragraph()
                        extra.paragraph_format.left_indent = Pt(10)
                        run = extra.add_run(f"- {line}")
                        run.italic = True
                        run.font.size = Pt(10)
                para.paragraph_format.space_after = Pt(2)
                _cell(row[3], str(part["marks"]), align=WD_ALIGN_PARAGRAPH.CENTER)
                _cell(row[4], part["bloom"], align=WD_ALIGN_PARAGRAPH.CENTER)
                _cell(row[5], module.get("co", ""), align=WD_ALIGN_PARAGRAPH.CENTER)
    centered("* * * * *", 12, space=0).paragraph_format.space_before = Pt(10)
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
