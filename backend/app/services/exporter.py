"""Question-bank exports for faculty: CSV, JSON and a print-ready DOCX paper."""
import csv
import io
import json

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor

TYPE_LABEL = {"mcq": "Multiple Choice", "tf": "True / False", "short": "Short Answer"}


def _rows(questions):
    for q in questions:
        yield {
            "id": q.id, "topic": q.topic.name, "type": q.qtype, "difficulty": q.difficulty, "bloom": q.bloom,
            "question": q.text, "options": q.options or [], "answer": q.answer, "explanation": q.explanation,
            "source_excerpt": q.source_excerpt, "status": q.status, "generated_by": q.origin,
        }


def to_json(course, questions) -> bytes:
    payload = {"course": course.name, "code": course.code, "questions": list(_rows(questions))}
    return json.dumps(payload, indent=2, ensure_ascii=False).encode("utf-8")


def to_csv(course, questions) -> bytes:
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(["#", "Topic", "Type", "Difficulty", "Bloom level", "Question", "Option A", "Option B",
                     "Option C", "Option D", "Answer", "Explanation", "Status", "Generated by"])
    for i, r in enumerate(_rows(questions), 1):
        opts = (r["options"] + [""] * 4)[:4]
        writer.writerow([i, r["topic"], r["type"], r["difficulty"], r["bloom"], r["question"], *opts,
                         r["answer"], r["explanation"], r["status"], r["generated_by"]])
    return ("﻿" + buf.getvalue()).encode("utf-8")


def to_docx(course, questions, include_answers: bool = True) -> bytes:
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(11)

    title = doc.add_heading(course.name, level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    sub = doc.add_paragraph(f"{course.code + ' · ' if course.code else ''}Question Bank · {len(questions)} questions")
    sub.alignment = WD_ALIGN_PARAGRAPH.CENTER

    by_topic: dict[str, list] = {}
    for q in questions:
        by_topic.setdefault(q.topic.name, []).append(q)

    n = 0
    key: list[tuple[int, str, str]] = []
    for topic, items in by_topic.items():
        doc.add_heading(topic, level=1)
        for q in items:
            n += 1
            p = doc.add_paragraph()
            p.add_run(f"{n}. ").bold = True
            p.add_run(q.text)
            tag = p.add_run(f"   [{q.difficulty.title()} · {q.bloom.title()} · {TYPE_LABEL.get(q.qtype, q.qtype)}]")
            tag.font.size = Pt(8)
            tag.font.color.rgb = RGBColor(0x6B, 0x72, 0x80)
            if q.qtype == "mcq":
                for letter, opt in zip("ABCD", q.options or []):
                    doc.add_paragraph(f"({letter}) {opt}").paragraph_format.left_indent = Pt(22)
                idx = (q.options or []).index(q.answer) if q.answer in (q.options or []) else -1
                answer = f"({'ABCD'[idx]}) {q.answer}" if idx >= 0 else q.answer
            elif q.qtype == "tf":
                doc.add_paragraph("True  /  False").paragraph_format.left_indent = Pt(22)
                answer = q.answer
            else:
                doc.add_paragraph("_" * 70).paragraph_format.left_indent = Pt(22)
                answer = q.answer
            key.append((n, answer, q.explanation))

    if include_answers and key:
        doc.add_page_break()
        doc.add_heading("Answer Key", level=1)
        for num, answer, explanation in key:
            p = doc.add_paragraph()
            p.add_run(f"{num}. ").bold = True
            p.add_run(answer)
            if explanation:
                note = p.add_run(f"\n{explanation}")
                note.italic = True
                note.font.size = Pt(9)
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


